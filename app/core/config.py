"""
Основной модуль конфигурации приложения

Данный модуль содержит базовые настройки и параметры конфигурации приложения.
Все конфигурационные параметры загружаются из переменных окружения, что
обеспечивает безопасность и гибкость настройки приложения.

Основные возможности модуля:
* Централизованное хранение конфигурационных параметров
* Автоматическое получение значений из переменных окружения
"""

import os
from pathlib import Path


class Config:
    """
    Базовый класс конфигурации приложения

    Класс представляет собой базовый объект для хранения и управления
    конфигурационными параметрами приложения. Все параметры загружаются
    из переменных окружения для обеспечения безопасности и гибкости настройки.

    Атрибуты:
        BASE_DIR: Корневая директория проекта
        SECRET_KEY: Секретный ключ приложения
        DEBUG: Флаг режима отладки
    """

    BASE_DIR = Path(__file__).parent.parent.parent
    """
    Базовая директория проекта

    Представляет собой путь к корневой директории проекта. Используется
    для построения относительных путей к файлам и ресурсам приложения.
    """

    SECRET_KEY: str = os.getenv('SECRET_KEY')
    """
    Секретный ключ приложения

    Критически важный параметр безопасности, используемый для:
    * Подписи токенов
    * Защиты сессий
    * Криптографической защиты данных

    Важно: ключ должен быть уникальным и храниться в безопасном месте.
    """

    DEBUG: bool = os.getenv('DEBUG', default=False)
    """
    Режим отладки приложения

    Определяет режим работы приложения:
    True - режим отладки (включает дополнительные логи и отладочную информацию)
    False - рабочий режим (минимальный вывод информации)

    Рекомендуется использовать только в процессе разработки.
    """

    TEMPLATES_FOLDER: str = BASE_DIR / (
        os.getenv('TEMPLATES_FOLDER') or 'templates'
    )
    """
    Путь к директории с шаблонами

    Формирование пути:
    - берётся корневая директория проекта (BASE_DIR);
    - к ней присоединяется значение переменной окружения TEMPLATES_FOLDER.

    Пример:
    Если BASE_DIR = /home/user/myapp, а TEMPLATES_FOLDER = "templates",
    то TEMPLATES_FOLDER будет равен /home/user/myapp/templates.

    Важно:
    - переменная окружения TEMPLATES_FOLDER должна быть задана
        в среде выполнения;
    - директория должна существовать физически,
        иначе приложение может выдать ошибку при попытке доступа к шаблонам.
    """

    DATABASE_URL: str = os.getenv('DATABASE_URL')
    """
    URL подключения к базе данных

    Важно:
    - значение должно быть задано в переменных окружения в среде выполнения;
    - запрещено хранить значение в коде приложения из соображений безопасности;
    """
