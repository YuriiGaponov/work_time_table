"""
Модуль содержит набор тестовых сценариев для проверки HTTP-маршрутов
веб‑приложения.

Назначение:
- верификация доступности ключевых эндпоинтов;
- контроль корректности возвращаемых HTTP-статусов.

Особенности реализации:
- используются фикстуры тестового клиента (`client`) из фреймворка pytest;
- для проверки статусов применяется стандартное перечисление `http.HTTPStatus`.
"""

from http import HTTPStatus


class TestRoutes:
    """
    Набор тестовых кейсов для проверки маршрутизации веб‑приложения.

    Класс объединяет методы, тестирующие отдельные HTTP-эндпоинты.
    Каждый метод:
    - выполняет запрос к определённому URL;
    - проверяет соответствие полученного HTTP-статуса ожидаемому значению.

    Зависимости:
    - `client`: тестовый клиент для имитации HTTP-запросов
        (передаётся как параметр);
    - `HTTPStatus`: перечисление стандартных кодов состояния HTTP.

    Конвенция именования тестов: `test_<описание_проверяемого_маршрута>`.
    """

    @classmethod
    def test_index_page(cls, client):
        """
        Проверяет доступность главной страницы приложения (маршрута `/`).

        Сценарий теста:
        1. Отправляет GET-запрос к корневому URL (`/`).
        2. Проверяет, что сервер возвращает статус 200 OK.

        Параметры:
        - cls: ссылка на класс (требуется для @classmethod);
        - client: экземпляр тестового клиента для выполнения HTTP-запросов.

        Ожидаемый результат:
        - Код ответа HTTP: HTTPStatus.OK (200).

        Поведение при ошибке:
        - Если статус отличается от 200,
            тест завершается с ошибкой утверждения (AssertionError).
        """
        response = client.get('/')
        assert response.status_code == HTTPStatus.OK
