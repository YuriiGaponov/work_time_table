"""
Этот модуль содержит тесты для проверки базового функционирования
основного приложения (app). Тесты гарантируют, что приложение корректно
инициализировано и доступно в тестовом окружении.
"""


class TestMainApp:
    """
    Набор тестов для проверки основного приложения (app).

    Класс содержит тесты, направленные на верификацию корректной
    инициализации и доступности экземпляра приложения в тестовом контексте.
    Все тесты являются классовыми методами, так как не требуют состояния
    экземпляра для выполнения проверок.

    Атрибуты:
        app: экземпляр приложения, импортированный из conftest.
            Используется во всех тестовых методах для проверки состояния.
    """

    @classmethod
    def test_app_exists(cls, app):
        """
        Проверяет, что экземпляр приложения (app) успешно создан и доступен.

        Тест убеждается, что переменная `app` не является None,
        что свидетельствует о корректной инициализации приложения
        в тестовом окружении.

        Аргументы:
            app: экземпляр приложения, передаваемый из тестового окружения
                (обычно через фикстуры pytest).

        Raises:
            AssertionError: если `app` равен None, это означает
                неудачную инициализацию приложения.

        Пример:
            >>> test_app_exists(app)  # Проходит, если app инициализирован
            >>> test_app_exists(None)  # Вызывает AssertionError
        """
        assert app is not None
